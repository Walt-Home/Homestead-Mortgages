/**
 * `node:crypto`, as much of it as the environments touch, for the browser.
 *
 * The environments hash their rulebooks and tool lists when their modules
 * load (`sha256` in `src/record.ts`), and the servicing app's ported
 * cashiering and the kernel's event store mint ids with `randomUUID`. Both
 * must be synchronous, because they run at module scope and inside the
 * engine, so the hash is SHA-256 written out in plain JavaScript rather than
 * Web Crypto's `subtle.digest`, which is asynchronous. A test holds it equal
 * to Node's on the rulebooks and on many other strings.
 */

